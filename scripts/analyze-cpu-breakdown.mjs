#!/usr/bin/env node
/**
 * CPU Percentage Breakdown Analyzer.
 *
 * Reads profiling snapshots from logs/profiling/ and computes two metrics per scope:
 *   1. avgPctFrameBudget  — Average % of the 16.67ms frame budget (how "hot" is it on average?)
 *   2. cumPctAllTime      — Cumulative % of all tracked CPU time (how much of total work is it?)
 *
 * Output: console table + reports/cpu-breakdown.json (paste to Claude for analysis).
 *
 * Usage:
 *   node scripts/analyze-cpu-breakdown.mjs
 *   node scripts/analyze-cpu-breakdown.mjs --top 20
 *   node scripts/analyze-cpu-breakdown.mjs --session <filename.json>
 *   node scripts/analyze-cpu-breakdown.mjs --output reports/my-breakdown.json
 *
 * Methodology:
 *   - Each profiling sample contains scope timings sampled at a single point in time (1 frame worth).
 *   - avgMs          = totalMs across all samples / sampleCount (average per sample window)
 *   - avgPctBudget   = (avgMs / 16.67ms) * 100
 *   - cumPctAllTime  = (scope's totalMs across all samples / sum of all scopes' totalMs) * 100
 *
 * Data source: logs/profiling/*.json (written by ProfilingPersistence → /api/profiling-snapshot)
 * Fallback:    logs/profiling/ README explains the format if no data exists yet.
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const PROJECT_ROOT = path.resolve(__dirname, '..');
const PROFILING_DIR = path.join(PROJECT_ROOT, 'logs/profiling');
const REPORTS_DIR = path.join(PROJECT_ROOT, 'reports');

// 60fps frame budget
const FRAME_BUDGET_MS = 1000 / 60; // 16.667ms

// ---------------------------------------------------------------------------
// CLI argument parsing
// ---------------------------------------------------------------------------

function parseArgs() {
  const args = process.argv.slice(2);
  const config = {
    top: 25,
    session: null,       // Filter to a specific session filename
    output: path.join(REPORTS_DIR, 'cpu-breakdown.json'),
  };

  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--top' && args[i + 1]) {
      config.top = parseInt(args[i + 1], 10);
      i++;
    } else if (args[i] === '--session' && args[i + 1]) {
      config.session = args[i + 1];
      i++;
    } else if (args[i] === '--output' && args[i + 1]) {
      config.output = args[i + 1];
      i++;
    } else if (args[i] === '--help') {
      printHelp();
      process.exit(0);
    }
  }

  return config;
}

function printHelp() {
  console.log(`
CPU Percentage Breakdown Analyzer
Usage: node scripts/analyze-cpu-breakdown.mjs [options]

Options:
  --top <n>           Show top N scopes (default: 25)
  --session <file>    Analyze only a specific session file (default: all)
  --output <path>     Output JSON path (default: reports/cpu-breakdown.json)
  --help              Show this help

Output metrics:
  avgPctFrameBudget   Average % of the 16.67ms frame budget used by this scope
  cumPctAllTime       Cumulative % of all tracked CPU time consumed by this scope
  avgMs               Average milliseconds per sample window
  totalMs             Total milliseconds across all samples
  sampleCount         Number of samples this scope appeared in

Data source: logs/profiling/*.json
  (Generated by ProfilingPersistence during gameplay, sent to /api/profiling-snapshot)
`);
}

// ---------------------------------------------------------------------------
// Data loading
// ---------------------------------------------------------------------------

function loadSnapshots(sessionFilter) {
  if (!fs.existsSync(PROFILING_DIR)) {
    return { error: `Profiling directory not found: ${PROFILING_DIR}`, snapshots: [] };
  }

  const files = fs.readdirSync(PROFILING_DIR)
    .filter((f) => f.endsWith('.json'))
    .filter((f) => !sessionFilter || f === sessionFilter)
    .sort();

  if (files.length === 0) {
    if (sessionFilter) {
      return { error: `Session file not found: ${sessionFilter}`, snapshots: [] };
    }
    return {
      error: [
        'No profiling snapshots found.',
        '',
        'To generate profiling data:',
        '  1. Start the game server: npm run server',
        '  2. Play a game (ProfilingPersistence samples every 5s)',
        '  3. When game over, data is POSTed to /api/profiling-snapshot',
        '  4. Run this script again',
        '',
        'The ProfilingOverlay (F9 in-game) shows real-time data but does not persist it.',
        'ProfilingPersistence (automatic) persists to disk.',
      ].join('\n'),
      snapshots: [],
    };
  }

  const snapshots = [];
  for (const file of files) {
    try {
      const filepath = path.join(PROFILING_DIR, file);
      const raw = fs.readFileSync(filepath, 'utf8');
      const session = JSON.parse(raw);
      if (session.samples && Array.isArray(session.samples)) {
        snapshots.push({ file, session });
      }
    } catch (err) {
      console.warn(`Warning: Failed to parse ${file}: ${err.message}`);
    }
  }

  return { snapshots };
}

// ---------------------------------------------------------------------------
// Analysis: aggregate scope data across all sessions/samples
// ---------------------------------------------------------------------------

/**
 * Aggregate scope timings across all samples in all sessions.
 *
 * Returns a Map<label, { totalMs, sampleCount, minMs, maxMs }>
 * Each "sample" is one 5-second snapshot window (contains 1 frame of timing data).
 */
function aggregateAllScopes(snapshots) {
  const scopeMap = new Map();
  let totalSamplesScanned = 0;

  for (const { session } of snapshots) {
    for (const sample of session.samples) {
      totalSamplesScanned++;

      for (const scope of sample.scopes) {
        if (!scope.label || scope.totalMs == null) continue;

        if (!scopeMap.has(scope.label)) {
          scopeMap.set(scope.label, {
            totalMs: 0,
            sampleCount: 0,
            minMs: Infinity,
            maxMs: 0,
          });
        }

        const entry = scopeMap.get(scope.label);
        entry.totalMs += scope.totalMs;
        entry.sampleCount += 1;
        if (scope.totalMs < entry.minMs) entry.minMs = scope.totalMs;
        if (scope.totalMs > entry.maxMs) entry.maxMs = scope.totalMs;
      }
    }
  }

  return { scopeMap, totalSamplesScanned };
}

/**
 * Compute final metrics for each scope.
 *
 * Metrics:
 *   avgMs             = totalMs / sampleCount
 *   avgPctFrameBudget = (avgMs / 16.67ms) * 100
 *   cumPctAllTime     = (scope.totalMs / sum_all_scopes.totalMs) * 100
 */
function computeMetrics(scopeMap) {
  // Sum of all tracked time (denominator for cumulative %)
  let grandTotalMs = 0;
  for (const entry of scopeMap.values()) {
    grandTotalMs += entry.totalMs;
  }

  const results = [];
  for (const [label, entry] of scopeMap.entries()) {
    const avgMs = entry.totalMs / entry.sampleCount;
    const avgPctFrameBudget = (avgMs / FRAME_BUDGET_MS) * 100;
    const cumPctAllTime = grandTotalMs > 0 ? (entry.totalMs / grandTotalMs) * 100 : 0;

    results.push({
      scope: label,
      avgMs: Math.round(avgMs * 1000) / 1000,
      avgPctFrameBudget: Math.round(avgPctFrameBudget * 10) / 10,
      cumPctAllTime: Math.round(cumPctAllTime * 10) / 10,
      totalMs: Math.round(entry.totalMs * 100) / 100,
      sampleCount: entry.sampleCount,
      minMs: entry.minMs === Infinity ? 0 : Math.round(entry.minMs * 1000) / 1000,
      maxMs: Math.round(entry.maxMs * 1000) / 1000,
    });
  }

  // Sort by cumulative % descending (biggest time consumers first)
  results.sort((a, b) => b.cumPctAllTime - a.cumPctAllTime);

  return { results, grandTotalMs };
}

// ---------------------------------------------------------------------------
// Rendering: console table
// ---------------------------------------------------------------------------

function padRight(str, len) {
  return String(str).padEnd(len);
}

function padLeft(str, len) {
  return String(str).padStart(len);
}

function printTable(results, topN, grandTotalMs, totalSamplesScanned, sessions) {
  const displayed = results.slice(0, topN);
  const coveredPct = displayed.reduce((sum, r) => sum + r.cumPctAllTime, 0);

  console.log('\n' + '='.repeat(82));
  console.log('  CPU PERCENTAGE BREAKDOWN');
  console.log('='.repeat(82));
  console.log(`  Sessions:  ${sessions.length}   Samples: ${totalSamplesScanned}   Total tracked time: ${(grandTotalMs / 1000).toFixed(1)}s`);
  console.log(`  Top ${topN} scopes shown (covering ${coveredPct.toFixed(1)}% of tracked CPU time)`);
  console.log('-'.repeat(82));
  console.log(
    `  ${'SCOPE'.padEnd(30)} ${'AVG%BUDGET'.padStart(10)} ${'CUM%TIME'.padStart(9)} ${'AVG_MS'.padStart(8)} ${'SAMPLES'.padStart(8)}`
  );
  console.log('-'.repeat(82));

  for (const r of displayed) {
    const bar = renderBar(r.cumPctAllTime, 15);
    console.log(
      `  ${padRight(r.scope, 30)} ${padLeft(r.avgPctFrameBudget.toFixed(1) + '%', 10)} ` +
      `${padLeft(r.cumPctAllTime.toFixed(1) + '%', 9)} ` +
      `${padLeft(r.avgMs.toFixed(2) + 'ms', 8)} ` +
      `${padLeft(r.sampleCount, 8)}  ${bar}`
    );
  }

  if (results.length > topN) {
    const rest = results.slice(topN);
    const restPct = rest.reduce((sum, r) => sum + r.cumPctAllTime, 0);
    console.log('-'.repeat(82));
    console.log(`  ${'... ' + (results.length - topN) + ' more scopes'.padEnd(29)} ${''.padStart(10)} ${padLeft(restPct.toFixed(1) + '%', 9)}`);
  }

  console.log('='.repeat(82));
  console.log('\nMETHODOLOGY:');
  console.log('  avgPctFrameBudget = (avgMs / 16.67ms) × 100');
  console.log('  cumPctAllTime     = (scope totalMs / sum of all scopes totalMs) × 100');
  console.log('  Each sample = 5-second window, 1 frame of timing data captured by ProfilingPersistence\n');
}

function renderBar(pct, maxChars) {
  const blocks = Math.round((pct / 100) * maxChars);
  return '█'.repeat(Math.min(blocks, maxChars));
}

// ---------------------------------------------------------------------------
// Export: reports/cpu-breakdown.json
// ---------------------------------------------------------------------------

function exportBreakdown(results, sessions, totalSamplesScanned, grandTotalMs, outputPath) {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });

  const output = {
    generated_at: new Date().toISOString(),
    methodology: {
      description: 'CPU time breakdown from profiling snapshots (ProfilingPersistence)',
      sample_interval_seconds: 5,
      frame_budget_ms: FRAME_BUDGET_MS,
      avgPctFrameBudget: 'avg_ms / 16.67ms × 100  — how much of a frame this scope uses on average',
      cumPctAllTime: 'scope_total_ms / all_scopes_total_ms × 100  — proportion of all tracked CPU time',
    },
    summary: {
      sessions_analyzed: sessions.length,
      session_files: sessions.map((s) => ({
        file: s.file,
        commit: s.session.metadata?.gitCommitShort,
        branch: s.session.metadata?.gitBranch,
        timestamp: s.session.metadata?.timestamp,
        duration_s: s.session.metadata?.sessionDuration,
        samples: s.session.samples.length,
      })),
      total_samples: totalSamplesScanned,
      grand_total_tracked_ms: Math.round(grandTotalMs * 100) / 100,
      total_scopes_tracked: results.length,
    },
    breakdowns: results.map((r, i) => ({
      rank: i + 1,
      scope: r.scope,
      avgPctFrameBudget: r.avgPctFrameBudget,
      cumPctAllTime: r.cumPctAllTime,
      avgMs: r.avgMs,
      minMs: r.minMs,
      maxMs: r.maxMs,
      totalMs: r.totalMs,
      sampleCount: r.sampleCount,
    })),
  };

  fs.writeFileSync(outputPath, JSON.stringify(output, null, 2));
  return output;
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

function main() {
  const config = parseArgs();

  // Load data
  const { snapshots, error } = loadSnapshots(config.session);

  if (error) {
    console.error('\nERROR:', error);
    process.exit(1);
  }

  console.log(`\nLoaded ${snapshots.length} profiling session(s).`);

  // Aggregate
  const { scopeMap, totalSamplesScanned } = aggregateAllScopes(snapshots);

  if (scopeMap.size === 0) {
    console.error('No scope data found in loaded sessions. Sessions may be empty.');
    process.exit(1);
  }

  // Compute metrics
  const { results, grandTotalMs } = computeMetrics(scopeMap);

  // Print table
  printTable(results, config.top, grandTotalMs, totalSamplesScanned, snapshots);

  // Export JSON
  const output = exportBreakdown(results, snapshots, totalSamplesScanned, grandTotalMs, config.output);
  console.log(`\nExported to: ${config.output}`);
  console.log(`Paste the JSON contents to Claude for analysis, or share the file path.\n`);

  return output;
}

main();
